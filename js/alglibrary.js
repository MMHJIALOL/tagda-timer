/**
 * Put a generated set in the registry, with the behaviour a data file cannot
 * carry. Exported for tools/import-cubingapp.mjs, which verifies a set by
 * registering it exactly the way the page will.
 */
export async function registerSet(data) {
  const puzzle = data.puzzle || 'cube';
  if (puzzle !== 'cube' && !PUZ) PUZ = await import('./puzzles.js');
  SETS[data.id] = {
    ...data,
    puzzle,
    adjust: data.adjust || { pre: [''], post: [''] },
    greySet: puzzle === 'cube' && data.gray ? new Set(data.gray) : null,
    groupOf: (c) => c.group,
    caseLabel: (c) => c.name,
    describe: (c) => c.group || '',
  };
  return SETS[data.id];
}

/**
 * Get a set, fetching its module the first time it is asked for, and its
 * extra algorithms if it has any. Already-loaded sets resolve without a
 * network round trip.
 */
export async function loadSet(id) {
  if (!SETS[id]) {
    if (GENERATED.has(id)) {
      const { SET } = await import(`./algsets/${id}.js`);
      if (!SETS[id]) await registerSet(SET);
    } else if (MODULES[id]) {
      const mod = await MODULES[id]();
      /* Folded in only where absent, so a set that has already had its extra
         algorithms attached is never replaced by a bare copy of itself. */
      for (const [k, v] of Object.entries(mod.SETS || { [mod.SET.id]: mod.SET })) {
        if (!SETS[k]) SETS[k] = v;
      }
    }
  }
  const set = SETS[id];
  if (set && MERGED.has(id) && !set.extra) {
    try {
      set.extra = (await import(`./algsets/more-${id}.js`)).EXTRA;
    } catch (err) {
      /* The set is still whole without them — this only costs alternates. */
      console.warn('[alglibrary] extra algorithms unavailable for', id, err.message);
      set.extra = {};
    }
  }
  return set || null;
}

/** Load every set the catalogue lists. Only the verification harness wants this. */
export async function loadAllSets() {
  for (const id of SET_IDS) await loadSet(id);
  return SETS;
}

/** Which set a case id belongs to. Case ids are unique across every set. */
export function setOf(caseId) {
  for (const set of Object.values(SETS)) {
    if (set.cases.some(c => c.id === caseId)) return set;
  }
  return null;
}

export const caseOf = (setId, caseId) =>
  (SETS[setId]?.cases || []).find(c => c.id === caseId) || null;

/**
 * The scrambled state that defines a case: its setup, if it has one, then the
 * case's own alg run backwards. That is exactly how the trainer builds a case
 * scramble (see the header of algs.js), so "solves this case" here means the
 * same thing it means on the timer screen.
 */
export const casePattern = (setId, caseId) => {
  const set = SETS[setId];
  const c = caseOf(setId, caseId);
  if (!c) return null;
  const back = puzzleOf(set) === 'cube' ? invert(c.alg) : PUZ.invertMoves(set.puzzle, c.alg);
  return [c.setup, back].filter(Boolean).join(' ');
};

