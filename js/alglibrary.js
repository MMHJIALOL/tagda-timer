/* ===========================================================
   Tagda Timer — algorithm library core (no DOM in this file).

   Three layers, deliberately kept apart so none of them can clobber
   another:

     algs.js              one canonical alg per case, unchanged by this
                          feature — still the fallback everywhere.
     alglibrary-*.js,     community alternates, read-only, ship with the
     algsets/*.js         app. algsets/ is generated by
                          tools/import-cubingapp.mjs.
     IndexedDB `kv`       your drag order and your own algs, per device.

   Nothing here trusts an algorithm it has not executed. `verify()` runs
   the candidate against the case's own scrambled state on a simulated
   puzzle — cubenet.js for every cube size, puzzles.js for pyraminx, skewb
   and square-1 — and both the shipped files and the "add your own" box go
   through it. A wrong alg in a cubing app teaches someone the wrong thing,
   which is worse than a missing feature.
   =========================================================== */

