/* A second table for the orientation-only set: there "done" is one colour on
   top and one colour underneath, so the search has many goals rather than one.
   Both halves of that matter. Every corner facing the right way is not enough
   on its own — a top corner dropped into a bottom slot can be perfectly
   oriented and still put a white sticker in the middle of the yellow face, and
   an algorithm found against that weaker goal would not be a 2x2 OLL
   algorithm at all. So the goal set is: every corner oriented, and no corner
   in the other layer. */
const orientedGoals = [];
for (const top of permutations([URF, UFL, ULB, UBR])) {
  for (const bottom of permutations([DFR, DLF, DRB])) {
    const cp = [0,1,2,3,4,5,6,7];
    [URF, UFL, ULB, UBR].forEach((pos, i) => { cp[pos] = top[i]; });
    [DFR, DLF, DRB].forEach((pos, i) => { cp[pos] = bottom[i]; });
    orientedGoals.push({ state: { cp, co: [0,0,0,0,0,0,0,0] } });
  }
}
const orient = buildTable(orientedGoals);
console.log(`  oriented: ${orient.seen.toLocaleString()} states, depth ${orient.depth}`);

const D_SOLVED = {};
const D_ADJ    = { [DFR]: DLF, [DLF]: DFR };
const D_DIAG   = { [DLF]: DRB, [DRB]: DLF };

const unoriented = (s) => UP.some(p => s.co[p] !== 0);

function collect({ bottom, filter, table }) {
  const seen = new Set();
  const cases = [];
  for (const s of statesWithBottom(bottom)) {
    if (!filter(s)) continue;
    const key = orbitKey(s);
    if (seen.has(key)) continue;
    seen.add(key);
    const members = orbit(s);
    let best = null;
    for (const m of members) {
      const d = table.dist[m.idx];
      if (!best || d < best.d || (d === best.d && m.idx < best.idx)) best = { ...m, d };
    }
    cases.push({ state: best.state, depth: best.d, members: members.length });
  }
  return cases;
}

const ORI_ORDER = ['Sune', 'Antisune', 'T', 'U', 'L', 'Pi', 'H'];

function lastLayerSet(bottom) {
  const cases = collect({ bottom, filter: unoriented, table: solve });
  const byFamily = new Map();
  for (const c of cases) {
    const fam = ORI_NAME.get(oriOf(c.state)) || oriOf(c.state);
    if (!byFamily.has(fam)) byFamily.set(fam, []);
    byFamily.get(fam).push(c);
  }
  const rows = [];
  for (const fam of ORI_ORDER) {
    const list = (byFamily.get(fam) || []).sort((a, b) => a.depth - b.depth || indexOf(a.state) - indexOf(b.state));
    list.forEach((c, i) => {
      rows.push({
        family: fam,
        name: `${fam} ${i + 1}`,
        perm: topPerm(c.state),
        algs: algsFor(solve.dist, c.state, 4),
        depth: c.depth,
      });
    });
  }
  return rows;
}

const out = {};

out.CLL = lastLayerSet(D_SOLVED);
out.EG1 = lastLayerSet(D_ADJ);
out.EG2 = lastLayerSet(D_DIAG);

/* Orientation only: the bottom layer is already facing the right way, the top
   is not, and where the corners end up is the next step's problem. */
out.OLL = (() => {
  const cases = collect({ bottom: D_SOLVED, filter: unoriented, table: orient });
  // Orientation ignores permutation, so squash the orbit list down to one case
  // per twist pattern.
  const byOri = new Map();
  for (const c of cases) {
    const k = oriOf(c.state);
    const prev = byOri.get(k);
    if (!prev || c.depth < prev.depth) byOri.set(k, c);
  }
  return [...byOri.entries()]
    .map(([k, c]) => {
      const first = algsFor(orient.dist, c.state, 1)[0];
      /* The app defines a case as "the state this algorithm's inverse builds",
         because that is how it makes a trainer scramble. For a set whose
         algorithms finish the puzzle those are the same state; for an
         orientation set they are not — the algorithm leaves the corners in a
         different order than it found them, so its inverse is a *different*
         state with the same twist pattern. The alternates therefore have to be
         solutions of that state, not of the one the search started from, or
         every one of them but the first would be an algorithm for the case
         next door. */
      const pattern = modelOf(invert(first).split(' '));
      /* `first` came from a different search than the rest, so the stem rule
         in algsFor never saw it: `first` plus a closing U is the same alg. */
      const algs = [first, ...algsFor(orient.dist, pattern, 6)
        .filter(a => a !== first && stem(a) !== first && stem(a) !== stem(first))].slice(0, 4);
      return {
        family: ORI_NAME.get(k) || k,
        name: ORI_NAME.get(k) || k,
        perm: topPerm(c.state),
        algs,
        depth: c.depth,
      };
    })
    .sort((a, b) => ORI_ORDER.indexOf(a.family) - ORI_ORDER.indexOf(b.family));
})();

/* Both layers oriented, neither necessarily permuted. */
out.PBL = (() => {
  const rows = [];
  const bottoms = [['solved', D_SOLVED], ['adjacent swap', D_ADJ], ['diagonal swap', D_DIAG]];
  for (const [bname, bottom] of bottoms) {
    const cases = collect({ bottom, filter: (s) => !unoriented(s), table: solve });
    for (const c of cases) {
      if (c.depth === 0) continue;                       // already solved
      rows.push({
        family: `bottom ${bname}`,
        name: `${bname} / ${topPerm(c.state)}`,
        perm: topPerm(c.state),
        algs: algsFor(solve.dist, c.state, 4),
        depth: c.depth,
      });
    }
  }
  return rows;
})();

/* The last word is the app's own simulator, not this file's cube model: every
   algorithm is run against the state its case's first algorithm builds, and
   nothing is written if one of them comes up short. */
const DONE_CHECK = {
  OLL:  (f) => new Set(f.U.flat()).size === 1 && new Set(f.D.flat()).size === 1,
  PBL:  solvedFacelets, CLL: solvedFacelets, EG1: solvedFacelets, EG2: solvedFacelets,
};
function solvedFacelets(f) {
  return ['U','R','F','D','L','B'].every(F => f[F].flat().every(s => s === F));
}
const AUF_TOKENS = ['', 'U', 'U2', "U'"];
let failures = 0;
for (const [key, rows] of Object.entries(out)) {
  const done = DONE_CHECK[key];
  for (const r of rows) {
    const pattern = invert(r.algs[0]);
    for (const alg of r.algs) {
      const ok = AUF_TOKENS.some(pre => AUF_TOKENS.some(post =>
        done(faceletsFor([pattern, pre, alg, post].filter(Boolean).join(' '), 2))));
      if (!ok) { console.error(`  FAIL ${key} ${r.name}: ${alg}`); failures++; }
    }
  }
}
if (failures) { console.error(`${failures} algorithms failed the simulator check — nothing written.`); process.exit(1); }
console.log('every generated algorithm re-checked against js/cubenet.js: clean');

for (const [k, v] of Object.entries(out)) {
  console.log(`${k}: ${v.length} cases, ${v.reduce((n, r) => n + r.algs.length, 0)} algorithms, ` +
              `longest ${Math.max(...v.map(r => r.depth))} moves`);
}

