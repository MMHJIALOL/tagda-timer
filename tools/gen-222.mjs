/* ===========================================================
   Generate the 2x2 algorithm sets that ship in js/alglibrary-222.js
   and js/algs2.js.

       node tools/gen-222.mjs

   Nothing here is transcribed from a website or from memory. Every case
   is an equivalence class of real cube states, every algorithm is an
   exhaustive-search solution of that state, and every (case, algorithm)
   pair is re-checked at the end against js/cubenet.js — the same
   simulator the app itself verifies algorithms with. If the corner model
   below were wrong, that final check would fail rather than ship.

   The 2x2 group generated by <R, U, F> with the DBL corner pinned has
   3,674,160 states, which is small enough to hold a complete
   breadth-first distance table in memory, so every algorithm printed is
   optimal for its case in that move set.
   =========================================================== */

import { faceletsFor, stickerAt } from '../js/cubenet.js';

/* ---------------------------------------------------------
   Corner model.  URF UFL ULB UBR DFR DLF DBL DRB, DBL pinned.
   --------------------------------------------------------- */
const URF=0, UFL=1, ULB=2, UBR=3, DFR=4, DLF=5, DBL=6, DRB=7;
const NAMES = ['URF','UFL','ULB','UBR','DFR','DLF','DBL','DRB'];

const BASE = {
  U: { cp: [UBR, URF, UFL, ULB, DFR, DLF, DBL, DRB], co: [0,0,0,0,0,0,0,0] },
  R: { cp: [DFR, UFL, ULB, URF, DRB, DLF, DBL, UBR], co: [2,0,0,1,1,0,0,2] },
  F: { cp: [UFL, DLF, ULB, UBR, URF, DFR, DBL, DRB], co: [1,2,0,0,2,1,0,0] },
};

const SOLVED = { cp: [0,1,2,3,4,5,6,7], co: [0,0,0,0,0,0,0,0] };

/** a then b. */
function compose(a, b) {
  const cp = new Array(8), co = new Array(8);
  for (let i = 0; i < 8; i++) {
    cp[i] = a.cp[b.cp[i]];
    co[i] = (a.co[b.cp[i]] + b.co[i]) % 3;
  }
  return { cp, co };
}

/* The nine <R,U,F> moves, in the order the search tries them. */
const MOVES = [];
for (const face of ['R', 'U', 'F']) {
  let s = SOLVED;
  for (let i = 1; i <= 3; i++) {
    s = compose(s, BASE[face]);
    MOVES.push({ name: face + (i === 1 ? '' : i === 2 ? '2' : "'"), face, state: s });
  }
}

/* ---------------------------------------------------------
   Indexing.  7 moving corners: permutation (7!) x orientation (3^6).
   --------------------------------------------------------- */
const SLOT = [0, 1, 2, 3, 4, 5, -1, 6];       // cubie/position id -> 0..6, DBL dropped
const POS  = [0, 1, 2, 3, 4, 5, 7];           // 0..6 -> position id

const FACT = [1, 1, 2, 6, 24, 120, 720, 5040];
const N_PERM = 5040, N_ORI = 729, N_STATES = N_PERM * N_ORI;

function indexOf(s) {
  const p = POS.map(i => SLOT[s.cp[i]]);
  // Lehmer code
  let pi = 0;
  for (let i = 0; i < 7; i++) {
    let smaller = 0;
    for (let j = i + 1; j < 7; j++) if (p[j] < p[i]) smaller++;
    pi += smaller * FACT[6 - i];
  }
  let oi = 0;
  for (let i = 0; i < 6; i++) oi = oi * 3 + s.co[POS[i]];
  return pi * N_ORI + oi;
}

